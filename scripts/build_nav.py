"""Build the site menu and the section overview pages from page front matter.

Why: the site will grow to hundreds or thousands of topics. Nobody should
edit a hand-written menu. Each page says where it belongs; this script does
the rest.

What each page sets in its front matter
---------------------------------------
Section overview (docs/<section>/index.md):
    nav_title: "Core Automation"     # tab label
    order: 30                        # tab position (10, 20, 30 ... leaves gaps)

Topic (docs/<section>/<topic>/index.md) or page (docs/<section>/<page>.md):
    nav_title: "API testing"         # short menu label
    order: 20                        # position inside the section
    group: "API and databases"       # optional; if one topic in a section has
                                     # a group, every topic there must have one
    summary: "One plain sentence."   # shown on the section overview card
    level / status                   # shown as labels on the card

A page in docs/ itself can join a section with `nav_section: start-here`.
Lessons inside a topic: put more .md files (or folders with index.md) in the
topic folder, each with nav_title and order. They are listed under the topic.

Pages with `status: draft` ("Coming soon") stay out of the menu, the overview
cards and the README map. They are listed on docs/roadmap.md instead.

What it writes
--------------
1. zensical.toml: the `nav = [...]` block between the BEGIN/END nav markers,
   and the list of group names (the breadcrumb skips groups).
2. Each section overview: the topic cards between the BEGIN/END topics markers.
3. README.md: the topic map between the BEGIN/END topic map markers, with
   links to the public website.
4. docs/roadmap.md: every draft page, by section, between the roadmap markers.

Usage (from the repository root):
    .venv/bin/python scripts/build_nav.py           # update files
    .venv/bin/python scripts/build_nav.py --check   # fail if files are out of date
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

import yaml  # PyYAML, already installed with Zensical (requirements-docs.txt)

DOCS = Path("docs")
CONFIG = Path("zensical.toml")
FRONT_MATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)

NAV_BEGIN = "# BEGIN nav (generated by scripts/build_nav.py, do not edit by hand)"
NAV_END = "# END nav"
GROUPS_BEGIN = "# BEGIN nav groups (generated by scripts/build_nav.py, do not edit by hand)"
GROUPS_END = "# END nav groups"
CARDS_BEGIN = "<!-- BEGIN topics (generated by scripts/build_nav.py, do not edit by hand) -->"
CARDS_END = "<!-- END topics -->"
README = Path("README.md")
MAP_BEGIN = "<!-- BEGIN topic map (generated by scripts/build_nav.py, do not edit by hand) -->"
MAP_END = "<!-- END topic map -->"
ROADMAP = DOCS / "roadmap.md"
ROADMAP_BEGIN = "<!-- BEGIN roadmap (generated by scripts/build_nav.py, do not edit by hand) -->"
ROADMAP_END = "<!-- END roadmap -->"
LAST = 10**9  # pages without `order` go last, sorted by title


class NavError(Exception):
    """A page is missing something the menu needs."""


@dataclass
class Page:
    path: Path  # file inside docs/
    meta: dict
    children: list[Page] = field(default_factory=list)

    @property
    def rel(self) -> str:
        return self.path.relative_to(DOCS).as_posix()

    @property
    def title(self) -> str:
        title = self.meta.get("nav_title")
        if not title:
            raise NavError(f"{self.path}: add `nav_title:` to the front matter")
        return str(title)

    @property
    def draft(self) -> bool:
        return self.meta.get("status") == "draft"

    @property
    def sort_key(self) -> tuple:
        return (self.meta.get("order", LAST), self.title.lower())


def read_meta(path: Path) -> dict:
    match = FRONT_MATTER.match(path.read_text(encoding="utf-8"))
    return (yaml.safe_load(match.group(1)) or {}) if match else {}


def load_node(index: Path) -> Page:
    """A topic folder: its index.md plus any lessons inside it."""
    node = Page(index, read_meta(index))
    folder = index.parent
    for child in sorted(folder.iterdir()):
        if child.is_dir() and (child / "index.md").exists():
            node.children.append(load_node(child / "index.md"))
        elif child.suffix == ".md" and child.name != "index.md":
            node.children.append(Page(child, read_meta(child)))
    node.children.sort(key=lambda p: p.sort_key)
    return node


def load_sections() -> list[tuple[Page, list[Page]]]:
    """Every section (tab) with its topics, in order."""
    root_pages: dict[str, list[Page]] = {}
    for page in sorted(DOCS.glob("*.md")):
        meta = read_meta(page)
        if meta.get("nav_section"):
            root_pages.setdefault(meta["nav_section"], []).append(Page(page, meta))

    sections = []
    for folder in sorted(p for p in DOCS.iterdir() if p.is_dir()):
        index = folder / "index.md"
        if not index.exists():
            continue
        node = load_node(index)
        if "order" not in node.meta:
            continue  # not a section (e.g. docs/assets)
        topics = node.children + root_pages.pop(folder.name, [])
        topics.sort(key=lambda p: p.sort_key)
        sections.append((node, topics))
    if root_pages:
        raise NavError(f"nav_section names a section that does not exist: {sorted(root_pages)}")
    sections.sort(key=lambda s: s[0].sort_key)
    return sections


def published(pages: list[Page]) -> list[Page]:
    return [p for p in pages if not p.draft]


def published_sections(sections):
    return [(s, published(t)) for s, t in sections if not s.draft]


def grouped(section: Page, topics: list[Page]) -> list[tuple[str | None, list[Page]]]:
    """Split topics into groups, in the order the groups first appear."""
    with_group = [t for t in topics if t.meta.get("group")]
    if not with_group:
        return [(None, topics)]
    if len(with_group) != len(topics):
        missing = [t.rel for t in topics if not t.meta.get("group")]
        raise NavError(f"{section.path}: some topics have a group, these do not: {missing}")
    groups: dict[str, list[Page]] = {}
    for topic in topics:
        groups.setdefault(str(topic.meta["group"]), []).append(topic)
    return list(groups.items())


# ---------------------------------------------------------------- menu (TOML)


def toml_str(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)  # JSON strings are valid TOML strings


def nav_entry(page: Page, indent: int, in_group: bool = False) -> list[str]:
    pad = "  " * indent
    if not published(page.children):
        if in_group and page.path.name == "index.md":
            # The theme treats an index.md that comes first in a section as that
            # section's own page. Inside a group that would swallow the first
            # topic, so each topic gets its own one-page section.
            return [f"{pad}{{ {toml_str(page.title)} = [{toml_str(page.rel)}] }},"]
        return [f"{pad}{{ {toml_str(page.title)} = {toml_str(page.rel)} }},"]
    lines = [f"{pad}{{ {toml_str(page.title)} = [", f"{pad}  {toml_str(page.rel)},"]
    for child in published(page.children):
        lines += nav_entry(child, indent + 1)
    lines.append(f"{pad}] }},")
    return lines


def build_nav_block(sections) -> str:
    lines = [NAV_BEGIN, "nav = ["]
    for section, topics in sections:
        lines += [f"  {{ {toml_str(section.title)} = [", f"    {toml_str(section.rel)},"]
        for group, members in grouped(section, topics):
            if group is None:
                for topic in members:
                    lines += nav_entry(topic, 2)
            else:
                lines.append(f"    {{ {toml_str(group)} = [")
                for topic in members:
                    lines += nav_entry(topic, 3, in_group=True)
                lines.append("    ] },")
        lines.append("  ] },")
    lines += ["]", NAV_END]
    return "\n".join(lines)


def build_groups_block(sections) -> str:
    """Group names for the breadcrumb. A group may not share a name with a page."""
    names: list[str] = []
    for section, topics in sections:
        for group, _ in grouped(section, topics):
            if group is not None and group not in names:
                names.append(group)
    titles = {section.title for section, _ in sections}
    stack = [t for _, topics in sections for t in topics]
    while stack:
        page = stack.pop()
        titles.add(page.title)
        stack.extend(page.children)
    clash = sorted(set(names) & titles)
    if clash:
        raise NavError(f"a group has the same name as a page, rename one: {clash}")
    items = ", ".join(toml_str(n) for n in names)
    return f"{GROUPS_BEGIN}\nnav_groups = [{items}]\n{GROUPS_END}"


# ------------------------------------------------- section overview (cards)


def card(topic: Page, section: Page) -> str:
    summary = topic.meta.get("summary")
    if not summary:
        raise NavError(f"{topic.path}: add `summary:` (one plain sentence for the card)")
    # Links are relative to the section's index.md (docs/<section>/index.md).
    base = section.path.parent
    if topic.path.is_relative_to(base):
        target = topic.path.relative_to(base)
    else:  # a page in docs/ that joined with nav_section
        target = Path("..") / topic.path.relative_to(DOCS)
    chips = []
    if topic.meta.get("level"):
        chips.append(f'<span class="zts-chip">{topic.meta["level"]}</span>')
    if topic.meta.get("status") == "draft":
        chips.append('<span class="zts-chip zts-chip--soon">Coming soon</span>')
    lines = [
        f"-   [**{topic.title}**]({target.as_posix()})",
        "",
        f"    {summary}",
    ]
    if chips:
        lines += ["", "    " + " ".join(chips)]
    return "\n".join(lines)


def build_cards(section: Page, topics: list[Page]) -> str:
    parts = [CARDS_BEGIN, ""]
    for group, members in grouped(section, topics):
        if group is not None:
            parts += [f"## {group}", ""]
        parts += ['<div class="grid cards zts-topics" markdown>', ""]
        parts += [card(t, section) + "\n" for t in members]
        parts += ["</div>", ""]
    parts.append(CARDS_END)
    return "\n".join(parts)


# ------------------------------------------------------------- roadmap page


def drafts_in(page: Page) -> list[Page]:
    found = []
    for child in page.children:
        if child.draft:
            found.append(child)
        else:
            found += drafts_in(child)
    return found


def build_roadmap(sections) -> str:
    parts = [ROADMAP_BEGIN, ""]
    for section, topics in sections:
        items = [section] if section.draft else []
        for topic in topics:
            items += [topic] if topic.draft else drafts_in(topic)
        if not items:
            continue
        parts += [f"## {section.title}", ""]
        for page in items:
            target = page.path.relative_to(DOCS).as_posix()
            summary = page.meta.get("summary", "")
            parts.append(f"- [{page.title}]({target}): {summary}".rstrip(": "))
        parts.append("")
    parts.append(ROADMAP_END)
    return "\n".join(parts)


# ------------------------------------------------------- README topic map


def page_url(site_url: str, page: Page) -> str:
    """The public address of a page (the site uses folder-style addresses)."""
    rel = page.path.relative_to(DOCS).as_posix()
    folder = rel.removesuffix("index.md") if rel.endswith("index.md") else rel[:-3] + "/"
    return site_url + folder


def build_readme_map(sections, site_url: str) -> str:
    """One folded block per section, so the README stays short however many topics exist."""
    parts = [MAP_BEGIN, ""]
    for section, topics in sections:
        count = f"{len(topics)} topic{'s' if len(topics) != 1 else ''}"
        parts += [
            "<details>",
            f"<summary><b>{section.title}</b> ({count})</summary>",
            "",
            f"[Open the {section.title} overview]({page_url(site_url, section)})",
            "",
        ]
        for group, members in grouped(section, topics):
            if group is not None:
                parts += [f"**{group}**", ""]
            for topic in members:
                summary = topic.meta.get("summary", "")
                parts.append(f"- [{topic.title}]({page_url(site_url, topic)}): {summary}")
            parts.append("")
        parts += ["</details>", ""]
    parts += [f"Coming next: see the [Roadmap]({site_url}roadmap/).", ""]
    parts.append(MAP_END)
    return "\n".join(parts)


# ------------------------------------------------------------------- main


def replace_block(text: str, begin: str, end: str, block: str, where: Path) -> str:
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.DOTALL)
    if not pattern.search(text):
        raise NavError(f"{where}: markers not found. Add these two lines:\n  {begin}\n  {end}")
    return pattern.sub(lambda _: block, text, count=1)


def main() -> int:
    check = "--check" in sys.argv[1:]
    try:
        every_section = load_sections()
        sections = published_sections(every_section)
        updates: dict[Path, str] = {}
        config = CONFIG.read_text(encoding="utf-8")
        config = replace_block(config, NAV_BEGIN, NAV_END, build_nav_block(sections), CONFIG)
        config = replace_block(
            config, GROUPS_BEGIN, GROUPS_END, build_groups_block(sections), CONFIG
        )
        updates[CONFIG] = config
        site_url = tomllib.loads(config)["project"]["site_url"]
        updates[README] = replace_block(
            README.read_text(encoding="utf-8"),
            MAP_BEGIN,
            MAP_END,
            build_readme_map(sections, site_url),
            README,
        )
        updates[ROADMAP] = replace_block(
            ROADMAP.read_text(encoding="utf-8"),
            ROADMAP_BEGIN,
            ROADMAP_END,
            build_roadmap(every_section),
            ROADMAP,
        )
        for section, topics in sections:
            text = section.path.read_text(encoding="utf-8")
            updates[section.path] = replace_block(
                text, CARDS_BEGIN, CARDS_END, build_cards(section, topics), section.path
            )
    except NavError as err:
        print(f"build_nav: {err}", file=sys.stderr)
        return 1

    stale = [p for p, new in updates.items() if p.read_text(encoding="utf-8") != new]
    if check:
        if stale:
            print(
                "build_nav: out of date, run: .venv/bin/python scripts/build_nav.py",
                file=sys.stderr,
            )
            for p in stale:
                print(f"  {p}", file=sys.stderr)
            return 1
        print("build_nav: menu and overview pages are up to date")
        return 0
    for p in stale:
        p.write_text(updates[p], encoding="utf-8")
        print(f"updated {p}")
    topic_count = sum(len(t) for _, t in sections)
    print(f"{len(stale)} file(s) changed, {topic_count} topics in {len(sections)} sections")
    return 0


if __name__ == "__main__":
    sys.exit(main())
