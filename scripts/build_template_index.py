"""Build the Template index page from the templates/ folders, so it never goes stale.

Why: the site has hundreds of template files. A hand-kept list would miss new ones
on the first day. This script lists every file Git tracks under
modules/<section>/<topic>/templates/ (the page that owns a folder says `code: <section>/<topic>`
in its front matter), grouped like the menu, with one line saying
what each file is (taken from the file itself).

Writes
------
docs/toolbox/template-index/index.md   between the BEGIN/END template index markers

What the "what it is" line comes from
-------------------------------------
.py        the first line of the module docstring (or "Tests" for test files)
.md        the first "# " heading
.feature   the "Feature:" line
others     the first comment line after the credit line

Usage (from the repository root; new files must be `git add`ed first):
    .venv/bin/python scripts/build_template_index.py           # update the page
    .venv/bin/python scripts/build_template_index.py --check   # fail if out of date
"""

from __future__ import annotations

import ast
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import build_nav  # noqa: E402  (same folder; reuses the menu's page loader)

PAGE = Path("docs/toolbox/template-index/index.md")
BEGIN = (
    "<!-- BEGIN template index"
    " (generated by scripts/build_template_index.py, do not edit by hand) -->"
)
END = "<!-- END template index -->"
REPO = "https://github.com/myopensdet/myopensdet.github.io/blob/main/"
CREDIT = "Template from myOpenSDET"
SKIP_NAMES = {"__init__.py", ".gitignore"}
NAMES = {
    "requirements.txt": "Python packages to install: pip install -r requirements.txt",
    "pytest.ini": "pytest settings",
    "conftest.py": "Shared pytest fixtures",
    ".env.example": "Settings to copy into .env (no real secrets)",
    "Dockerfile": "How to build the Docker image",
    ".dockerignore": "Files Docker leaves out of the image",
    ".coveragerc": "Code coverage settings",
}
KINDS = {
    ".ini": "Settings",
    ".toml": "Settings",
    ".cfg": "Settings",
    ".txt": "Text file",
    ".csv": "Data (CSV)",
    ".json": "Data (JSON)",
    ".sql": "SQL",
    ".sh": "Shell script",
    ".yml": "YAML file",
    ".yaml": "YAML file",
    ".robot": "Robot Framework file",
    ".html": "Web page",
    ".xlsx": "Test data (Excel)",
}


def tracked_templates() -> list[Path]:
    out = subprocess.run(
        ["git", "ls-files", "modules/*/*/templates/*"],  # noqa: S607 (git from PATH, fixed args)
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return [Path(line) for line in out.splitlines() if Path(line).name not in SKIP_NAMES]


def first_comment(lines: list[str]) -> str:
    for line in lines[:12]:
        text = line.strip()
        for mark in ("# ", "-- ", "// ", "<!--"):
            if text.startswith(mark):
                text = text.removeprefix(mark).removesuffix("-->").strip()
                if text and CREDIT not in text and not text.startswith("!"):
                    return text
                break
    return ""


def first_sentence(doc: str) -> str:
    paragraph = " ".join(doc.strip().split("\n\n")[0].split())
    end = paragraph.find(". ")
    return paragraph if end == -1 else paragraph[: end + 1]


def describe(path: Path) -> str:
    if path.name in NAMES:
        return NAMES[path.name]
    if path.suffix == ".xlsx":
        return KINDS[".xlsx"]
    text = path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    if path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(text))
        except SyntaxError:
            doc = None
        if doc and not doc.startswith("<"):
            return first_sentence(doc)
        if doc:
            return "A starter to copy: fill in the parts marked < >"
        if path.name.startswith("test_"):
            return "Tests"
        return first_comment(lines) or "Python helper code"
    if path.suffix == ".md":
        heading = next((line[2:].strip() for line in lines if line.startswith("# ")), "")
        return heading or first_comment(lines) or "Notes"
    if path.suffix == ".feature":
        return next((line.strip() for line in lines if line.strip().startswith("Feature:")), "")
    return first_comment(lines) or KINDS.get(path.suffix, "File")


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("`", "")


def build_block() -> str:
    files = tracked_templates()
    by_topic: dict[str, list[Path]] = {}
    for path in files:
        section, topic = path.parts[1], path.parts[2]
        by_topic.setdefault(f"{section}/{topic}", []).append(path)

    lines = [BEGIN, "", f"**{len(files)} files in {len(by_topic)} topics.**", ""]
    for section, topics in build_nav.load_sections():
        rows = []
        # A page owns a code folder when its front matter says `code: <section>/<topic>`
        # (the folder in modules/). The section page itself can own one too.
        pages = [section]
        stack = list(topics)
        while stack:
            page = stack.pop(0)
            pages.append(page)
            stack[0:0] = page.children
        for topic in pages:
            key = topic.meta.get("code")
            paths = sorted(by_topic.pop(key, [])) if key else []
            if not paths:
                continue
            link = "../../" + topic.rel
            rows += [f'??? note "{topic.title} ({len(paths)} files)"', ""]
            rows += [f"    Open the guide: [{topic.title}]({link})", ""]
            rows += ["    | File | What it is |", "    | --- | --- |"]
            for path in paths:
                inside = Path(*path.parts[4:]).as_posix()
                file_link = f"[{cell(inside)}]({REPO}{path.as_posix()})"
                rows.append(f"    | {file_link} | {cell(describe(path))} |")
            rows.append("")
        if rows:
            lines += [f"## {section.title}", "", *rows]
    if by_topic:
        raise build_nav.NavError(
            f"code folders with no page (add `code:` to its front matter): {sorted(by_topic)}"
        )
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    check = "--check" in sys.argv
    try:
        block = build_block()
        old = PAGE.read_text(encoding="utf-8")
        new = build_nav.replace_block(old, BEGIN, END, block, PAGE)
    except build_nav.NavError as err:
        print(f"build_template_index: {err}")
        return 1
    if new == old:
        print("build_template_index: up to date")
        return 0
    if check:
        print("build_template_index: out of date. Run: python scripts/build_template_index.py")
        return 1
    PAGE.write_text(new, encoding="utf-8")
    print(f"build_template_index: updated {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
